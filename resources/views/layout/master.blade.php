  <script>
    document.addEventListener('change', function (e) {
      var input = e.target;
      if (!input.matches || !input.matches('input[type=file][data-max-mb]')) return;

      var maxMb = parseFloat(input.dataset.maxMb);
      var file = input.files[0];
      if (file && file.size > maxMb * 1024 * 1024) {
        alert('File terlalu besar (' + (file.size / 1024 / 1024).toFixed(1) +
          ' MB). Maksimal ' + maxMb + ' MB.');
        input.value = '';
      }
    });

    // Pengaman kedua: tahan submit kalau masih ada file kebesaran
    document.addEventListener('submit', function (e) {
      var inputs = e.target.querySelectorAll('input[type=file][data-max-mb]');
      for (var i = 0; i < inputs.length; i++) {
        var f = inputs[i].files[0];
        if (f && f.size > parseFloat(inputs[i].dataset.maxMb) * 1024 * 1024) {
          e.preventDefault();
          alert('File terlalu besar. Maksimal ' + inputs[i].dataset.maxMb + ' MB.');
          return;
        }
      }
    }, true);
  </script>

